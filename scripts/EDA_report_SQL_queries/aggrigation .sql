-- Q16. What is the average order value (AOV)?
-- Calculates average revenue per unique order.
-- Formula: Total Revenue / Total Unique Orders

SELECT
    ROUND(
        SUM(total_sales) * 1.0 / COUNT(DISTINCT order_id),
        2
    ) AS average_order_value
FROM gold.sales_table;
GO


-- Q17. What is the monthly sales growth rate?
-- Compares monthly revenue with the previous month
-- to calculate the percentage increase or decrease in sales.

WITH monthly_sales AS
(
    SELECT
        Order_Month,
        MONTH(order_date) AS month_number,
        SUM(total_sales) AS monthly_revenue
    FROM gold.sales_table
    GROUP BY
        Order_Month,
        MONTH(order_date)
),
monthly_growth AS
(
    SELECT
        Order_Month,
        month_number,
        monthly_revenue,

        LAG(monthly_revenue) OVER (
            ORDER BY month_number
        ) AS previous_month_revenue

    FROM monthly_sales
)

SELECT
    Order_Month,
    monthly_revenue,
    previous_month_revenue,

    CONCAT(
        ROUND(
            (
                monthly_revenue - previous_month_revenue
            ) * 100.0
            / NULLIF(previous_month_revenue, 0),
            2
        ),
        ' %'
    ) AS growth_rate_percentage

FROM monthly_growth
ORDER BY month_number;
GO


