-- Q19. What percentage of customers are repeat customers
--      versus one-time customers?
-- Classifies customers based on the number of unique orders they placed.
-- Calculates the number and percentage of customers in each category.

WITH customer_orders AS
(
    SELECT
        customer_id,
        COUNT(DISTINCT order_id) AS order_count
    FROM gold.sales_table
    GROUP BY customer_id
)

SELECT
    CASE
        WHEN order_count > 1 THEN 'Repeat Customer'
        ELSE 'One-Time Customer'
    END AS customer_type,

    COUNT(*) AS total_customers,

    CONCAT(
        ROUND(
            COUNT(*) * 100.0 / SUM(COUNT(*)) OVER(),
            2
        ),
        ' %'
    ) AS customer_percentage

FROM customer_orders

GROUP BY
    CASE
        WHEN order_count > 1 THEN 'Repeat Customer'
        ELSE 'One-Time Customer'
    END;
GO


-- Q20. Which age group has the highest average spending per customer?
-- First calculates the total spending of each customer,
-- then calculates the average spending of customers within each age group.
-- Excludes customers whose age category is unknown.

WITH customer_spending AS
(
    SELECT
        age_category,
        customer_id,
        SUM(total_sales) AS customer_total_spending
    FROM gold.sales_table
    WHERE age_category <> 'unknown'
    GROUP BY
        age_category,
        customer_id
)

SELECT TOP 1
    age_category,
    ROUND(
        AVG(customer_total_spending),
        2
    ) AS avg_customer_spending
FROM customer_spending
GROUP BY age_category
ORDER BY avg_customer_spending DESC;
GO


-- Q21. Which cities have a high customer base but relatively low revenue?
-- Compares each city's percentage of total customers
-- with its percentage of total revenue.
-- Highlights cities where customer contribution exceeds revenue contribution.

SELECT
    City,

    COUNT(DISTINCT customer_id) AS total_customers,

    ROUND(
        COUNT(DISTINCT customer_id) * 100.0
        / (
            SELECT COUNT(DISTINCT customer_id)
            FROM gold.sales_table
        ),
        2
    ) AS customer_percentage,

    SUM(total_sales) AS total_sales,

    ROUND(
        SUM(total_sales) * 100.0
        / (
            SELECT SUM(total_sales)
            FROM gold.sales_table
        ),
        2
    ) AS revenue_percentage

FROM gold.sales_table

GROUP BY City

HAVING
    COUNT(DISTINCT customer_id) * 100.0
    / (
        SELECT COUNT(DISTINCT customer_id)
        FROM gold.sales_table
    )
    >
    SUM(total_sales) * 100.0
    / (
        SELECT SUM(total_sales)
        FROM gold.sales_table
    )

ORDER BY
    total_customers DESC,
    total_sales ASC;
GO


-- Q22. What are the highest-value and lowest-value orders?
-- Aggregates sales at the order level before identifying
-- the highest- and lowest-value orders.

WITH order_values AS
(
    SELECT
        order_id,
        SUM(total_sales) AS order_value
    FROM gold.sales_table
    GROUP BY order_id
)

SELECT
    MAX(order_value) AS highest_value_order,
    MIN(order_value) AS lowest_value_order
FROM order_values;
GO


-- Q23. What percentage of total revenue is generated
--       by the top 10% of customers?
-- Aggregates revenue per customer, divides customers into ten groups
-- based on spending, and calculates the revenue contribution
-- of the highest-spending group.

WITH customer_revenue AS
(
    SELECT
        customer_id,
        SUM(total_sales) AS total_customer_revenue
    FROM gold.sales_table
    GROUP BY customer_id
),
customer_ranking AS
(
    SELECT
        customer_id,
        total_customer_revenue,

        NTILE(10) OVER (
            ORDER BY total_customer_revenue DESC
        ) AS revenue_rank

    FROM customer_revenue
)

SELECT
    COUNT(DISTINCT customer_id) AS top_10_percent_customers,

    SUM(total_customer_revenue) AS top_10_percent_revenue,

    CONCAT(
        ROUND(
            SUM(total_customer_revenue) * 100.0
            / (
                SELECT SUM(total_customer_revenue)
                FROM customer_revenue
            ),
            2
        ),
        ' %'
    ) AS revenue_contribution_percentage

FROM customer_ranking
WHERE revenue_rank = 1;
GO


